## update-flatpak-cli -- Flatpak CLI shortcut generator
##
## A compiled, dependency-free reimplementation of Stephen Sokolow's
## `update_flatpak_cli.py` gist.  It generates launchers with traditional
## (non-Flatpak) command names for your installed Flatpak applications, so that
## `flatpak run org.gnome.Builder` becomes plain `gnome-builder`, with
## `--file-forwarding` handled for you.
##
## Run it with no arguments for the original behaviour:
##
##     update-flatpak-cli
##
## See `--help` for the additions (dry-run, alternate roots, no-prune, ...).

import std/[options, os, sequtils, strutils, tables]

import fpcli/[desktop, flatpak, naming, pathscan, wrapper]

const
  ProgramName = "update-flatpak-cli"
  Version = "1.0.0"

type
  Config = object
    binDir: string
    sysRoot: string
    userRoot: string
    useSystem: bool
    useUser: bool
    dryRun: bool
    prune: bool          ## remove stale launchers we recognise as ours
    pruneAll: bool       ## remove every regular file in the output dir (1:1 with the original)
    listOnly: bool
    strict: bool         ## exit non-zero when anything was warned about
    quiet: bool
    verbose: bool
    force: bool          ## overwrite files we do not recognise as ours
    showHelp: bool
    showVersion: bool

  Counters = object
    written: int
    removed: int
    keptForeign: int
    collisions: int
    skipped: int
    apps: int

# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

var gQuiet = false
var gVerbose = false
var gWarnings = 0

proc note(msg: string) =
  if not gQuiet:
    stdout.writeLine(msg)

proc detail(msg: string) =
  if gVerbose and not gQuiet:
    stdout.writeLine(msg)

proc warn(msg: string) =
  inc gWarnings
  stderr.writeLine("WARNING: " & msg)

proc fail(msg: string) =
  stderr.writeLine("ERROR: " & msg)

# ---------------------------------------------------------------------------
# Path helpers
# ---------------------------------------------------------------------------

proc expandTilde(path: string): string =
  if path == "~":
    return getHomeDir()
  if path.startsWith("~/") or path.startsWith("~" & DirSep):
    return getHomeDir() / path[2 .. ^1]
  path

proc normalizeDir(path: string): string =
  ## Expand `~`, make absolute, collapse `.`/`..` and duplicates, and drop any
  ## trailing separator so comparisons against `$PATH` entries are reliable.
  var p = expandTilde(strip(path))
  if p.len == 0:
    return p
  p = normalizedPath(absolutePath(p))
  while p.len > 1 and p.endsWith(DirSep):
    p.setLen(p.len - 1)
  p

# ---------------------------------------------------------------------------
# Command line
# ---------------------------------------------------------------------------

const HelpText = """
""" & ProgramName & """ """ & Version & """ -- generate CLI launchers for Flatpak apps

USAGE
  """ & ProgramName & """ [OPTIONS]

With no options, this behaves like the Python original: it (re)generates a
launcher per installed Flatpak application in ~/.local/bin/flatpak.

OPTIONS
  -d, --bin-dir DIR       Output directory.
                          Default: ~/.local/bin/flatpak
      --system-root DIR   System Flatpak installation root.
                          Default: $FLATPAK_SYSTEM_DIR or /var/lib/flatpak
      --user-root DIR     User Flatpak installation root.
                          Default: $FLATPAK_USER_DIR or $XDG_DATA_HOME/flatpak
                          or ~/.local/share/flatpak
      --no-system         Ignore the system installation
      --no-user           Ignore the user installation
  -n, --dry-run           Report what would be done; touch nothing
      --no-prune          Keep existing generated launchers that are stale
      --prune-all         Delete *every* regular file in the output directory
                          (matches the original's sledgehammer behaviour)
  -f, --force             Overwrite files in the output directory that were not
                          generated by this tool
  -l, --list              List the app -> command mapping and exit
  -s, --strict            Exit 1 if any warning or collision occurred
  -v, --verbose           More detail
  -q, --quiet             Suppress progress output
  -h, --help              Show this help
  -V, --version           Show version

ENVIRONMENT
  FLATPAK_SYSTEM_DIR, FLATPAK_USER_DIR, XDG_DATA_HOME, PATH

EXIT STATUS
  0  success
  1  fatal error (or warnings with --strict)
  2  usage error
"""

proc usageError(msg: string): int =
  fail(msg)
  stderr.writeLine("Try '" & ProgramName & " --help' for usage.")
  2

proc parseArgs(params: seq[string]): tuple[cfg: Config, ok: bool, code: int] =
  result.cfg = Config(binDir: getHomeDir() / ".local" / "bin" / "flatpak",
                      sysRoot: defaultSystemRoot(),
                      userRoot: defaultUserRoot(),
                      useSystem: true,
                      useUser: true,
                      prune: true)

  var i = 0
  while i < params.len:
    let arg = params[i]
    inc i

    var key = arg
    var val = ""
    var hasVal = false
    if arg.startsWith("--") and arg.contains('='):
      let eq = arg.find('=')
      key = arg[0 ..< eq]
      val = arg[eq + 1 .. ^1]
      hasVal = true

    template takeValue(): string =
      block:
        var v = val
        if not hasVal:
          if i < params.len:
            v = params[i]
            inc i
          else:
            result.ok = false
            result.code = usageError("Option '" & key & "' requires a value")
            return
        v

    case key
    of "-h", "--help":
      result.cfg.showHelp = true
    of "-V", "--version":
      result.cfg.showVersion = true
    of "-d", "--bin-dir":
      let raw = takeValue()
      # Require an absolute path up front: the directory ends up in $PATH, and
      # a relative entry would silently mean different things per working
      # directory (and make our own path comparisons meaningless).
      if not isAbsolute(expandTilde(raw)):
        result.ok = false
        result.code = usageError("Output directory must be an absolute path: '" &
                                 raw & "'")
        return
      result.cfg.binDir = raw
    of "--system-root":
      result.cfg.sysRoot = takeValue()
    of "--user-root":
      result.cfg.userRoot = takeValue()
    of "--no-system":
      result.cfg.useSystem = false
    of "--no-user":
      result.cfg.useUser = false
    of "-n", "--dry-run":
      result.cfg.dryRun = true
    of "--no-prune":
      result.cfg.prune = false
    of "--prune-all":
      result.cfg.pruneAll = true
      result.cfg.prune = true
    of "-f", "--force":
      result.cfg.force = true
    of "-l", "--list":
      result.cfg.listOnly = true
    of "-s", "--strict":
      result.cfg.strict = true
    of "-v", "--verbose":
      result.cfg.verbose = true
    of "-q", "--quiet":
      result.cfg.quiet = true
    else:
      if arg.startsWith("-"):
        result.ok = false
        result.code = usageError("Unknown option '" & arg & "'")
        return
      result.ok = false
      result.code = usageError("Unexpected argument '" & arg &
                               "' (this tool takes no positional arguments)")
      return

  result.cfg.binDir = normalizeDir(result.cfg.binDir)
  result.cfg.sysRoot = normalizeDir(result.cfg.sysRoot)
  result.cfg.userRoot = normalizeDir(result.cfg.userRoot)
  result.ok = true

# ---------------------------------------------------------------------------
# Per-application emission
# ---------------------------------------------------------------------------

proc run(cfg: Config): int =
  gQuiet = cfg.quiet
  gVerbose = cfg.verbose
  gWarnings = 0

  # --- Guard rails around the output directory ---------------------------
  # This program deletes files in `binDir`.  Refuse to aim it at a location
  # that would be catastrophic, and require an absolute path so that a stray
  # relative path can never resolve against the caller's working directory.
  if not isAbsolute(cfg.binDir):
    fail("Output directory must be an absolute path: '" & cfg.binDir & "'")
    return 1
  if cfg.binDir == "/":
    fail("Refusing to use '" & cfg.binDir & "' as the output directory")
    return 1
  let home = normalizeDir(getHomeDir())
  if cfg.binDir == home or cfg.binDir == normalizeDir("/usr") or
     cfg.binDir == normalizeDir("/usr/bin") or cfg.binDir == normalizeDir("/bin"):
    fail("Refusing to manage launchers directly inside '" & cfg.binDir & "'")
    return 1

  # --- Installations -----------------------------------------------------
  var installations: seq[Installation]
  if cfg.useSystem:
    installations.add Installation(kind: ikSystem, root: cfg.sysRoot)
  if cfg.useUser:
    installations.add Installation(kind: ikUser, root: cfg.userRoot)

  # --- Applications ------------------------------------------------------
  note("Getting list of installed application/non-runtime packages...")
  var refs: seq[AppRef]
  for inst in installations:
    if not dirExists(inst.root / "app"):
      detail("  (" & $inst.kind & " installation not present: " & inst.root & ")")
      continue
    let found = discoverApps(inst)
    detail("  found " & $found.len & " application(s) in the " & $inst.kind &
           " installation (" & inst.root & ")")
    if inst.kind == ikUser:
      # A user installation shadows a system installation of the same app,
      # matching libflatpak's own precedence.
      var userIds: seq[string]
      for appRef in found:
        userIds.add appRef.id
      var kept: seq[AppRef]
      for appRef in refs:
        if appRef.id notin userIds:
          kept.add appRef
      refs = kept
    for appRef in found:
      refs.add appRef

  var counters = Counters(apps: refs.len)

  # --- Desktop file search path -----------------------------------------
  var desktopDirs: seq[string]
  for inst in installations:
    desktopDirs.add applicationsDir(inst)

  proc wantsUrlsFor(appRef: AppRef): bool =
    for dir in desktopDirs:
      let candidate = dir / (appRef.id & ".desktop")
      if fileExists(candidate) and desktopFileWantsUrls(candidate):
        return true
    false

  # --- Listing mode ------------------------------------------------------
  if cfg.listOnly:
    for appRef in refs:
      stdout.writeLine(prepareCmdName(appRef.command, appRef.id) & "\t" & appRef.id &
                       " (" & appRef.fullyQualified & ", command=" & appRef.command & ")")
      for extra in extraCmdsFor(appRef.id):
        stdout.writeLine(extra & "\t" & appRef.id & " (--command=" & extra & ")")
    if refs.len == 0:
      note("No installed Flatpak applications found.")
    return 0

  # --- Prepare the output directory -------------------------------------
  if not dirExists(cfg.binDir):
    if cfg.dryRun:
      note("[dry-run] would create " & cfg.binDir)
    else:
      try:
        createDir(cfg.binDir)
        detail("Created " & cfg.binDir)
      except OSError as e:
        fail("Cannot create output directory '" & cfg.binDir & "': " & e.msg)
        return 1

  # --- Prune stale launchers --------------------------------------------
  # Only files carrying our marker are removed, so a hand-written script that
  # happens to live in the same directory survives.  `--prune-all` restores the
  # original's behaviour of clearing every regular file.
  if cfg.prune and dirExists(cfg.binDir):
    var names: seq[string]
    try:
      for kind, sub in walkDir(cfg.binDir, relative = true):
        if kind == pcFile:
          names.add sub
    except OSError as e:
      fail("Cannot read output directory '" & cfg.binDir & "': " & e.msg)
      return 1

    for name in names:
      let path = cfg.binDir / name
      if isGeneratedFile(path):
        if cfg.dryRun:
          note("[dry-run] would remove stale launcher " & path)
          inc counters.removed
        elif removeGenerated(path):
          detail("Removed stale launcher " & path)
          inc counters.removed
        else:
          warn("Could not remove stale launcher '" & path & "'")
      elif cfg.pruneAll:
        if cfg.dryRun:
          note("[dry-run] would remove " & path)
          inc counters.removed
        else:
          try:
            removeFile(path)
            detail("Removed " & path)
            inc counters.removed
          except OSError:
            warn("Could not remove '" & path & "'")
      else:
        inc counters.keptForeign

  if counters.keptForeign > 0:
    detail("Left " & $counters.keptForeign & " unrecognised file(s) in " &
           cfg.binDir & " alone (use --prune-all to clear them)")

  # --- Generate ----------------------------------------------------------
  let dirs = pathDirs()
  let pathReport = analyzePath(cfg.binDir, dirs)
  var seen = initTable[string, string]()   # absolute path -> owner description

  proc emit(appRef: AppRef, candidate: string, extraCommand: string) =
    if hasTraversal(candidate):
      fail("Refusing to create a launcher for '" & appRef.id &
           "': command '" & candidate & "' traverses out of its directory")
      inc counters.skipped
      return

    # Flatpak's `command=` may be a path relative to /app (e.g. `bin/foo`), so
    # reduce it to a bare file name -- exactly as basename() did in the
    # original tool.
    let name = extractFilename(candidate)
    if name != candidate:
      detail("  reduced command path '" & candidate & "' to '" & name & "'")

    let invalid = validateCommandName(name)
    if invalid.isSome:
      fail("Refusing to create a launcher for '" & appRef.id & "': " &
           invalid.get)
      inc counters.skipped
      inc counters.collisions
      return

    let outPath = cfg.binDir / name
    if seen.hasKey(outPath):
      fail("Wrapper name \"" & outPath & "\" was already claimed by \"" &
           seen[outPath] & "\" and could not be mapped to \"" & appRef.id &
           "\". Please add a CMD_REMAPPINGS entry (see docs/CONFIGURATION.md).")
      inc counters.collisions
      return

    # Never clobber something we did not write, unless explicitly told to.
    if fileExists(outPath) and not isGeneratedFile(outPath) and not cfg.force:
      warn("Refusing to overwrite '" & outPath & "': it was not generated by " &
           "this tool. Use --force to replace it.")
      inc counters.skipped
      return

    let owner =
      if extraCommand.len > 0: appRef.id & " (--command=" & extraCommand & ")"
      else: appRef.id

    # Resolve the name *before* writing, so the warning below can tell
    # "something else already owns this command" apart from "the launcher we
    # are about to create is the one that owns it".
    let existing = findExecutable(name, dirs)

    if cfg.dryRun:
      note("[dry-run] would write " & outPath & " -> " & owner)
    else:
      let content = renderWrapper(appRef.id, extraCommand,
                                  wantsUrlsFor(appRef))
      if not writeLauncher(outPath, content):
        fail("Could not write launcher '" & outPath & "'")
        inc counters.skipped
        return
      detail("Wrote " & outPath & " -> " & owner)

    seen[outPath] = owner
    inc counters.written

    # Warn if this name is already taken by something else on $PATH.
    if existing.isSome and existing.get != outPath:
      var status: string
      if pathReport.missing:
        status = "The Flatpak wrapper will be inaccessible."
      else:
        let ownerIdx = dirs.find(parentDir(existing.get))
        if pathReport.binDirIndex <= ownerIdx:
          status = "The Flatpak wrapper will mask access to it."
        else:
          status = "The Flatpak wrapper will be inaccessible."
      warn("Command \"" & name & "\" already exists in your PATH at \"" &
           existing.get & "\". " & status)
      if cfg.verbose:
        note("  (compare shadowing may be resolved by editing $PATH order)")

  for appRef in refs:
    note("Generating wrapper for " & appRef.id & "...")
    let takesUrls = wantsUrlsFor(appRef)
    emit(appRef, prepareCmdName(appRef.command, appRef.id), "")
    for extra in extraCmdsFor(appRef.id):
      emit(appRef, extra, extra)

  # --- $PATH sanity ------------------------------------------------------
  if refs.len == 0:
    note("No installed Flatpak applications found (looked in " &
         installations.mapIt(it.root).join(", ") & ").")
  elif pathReport.missing:
    warn("Could not find " & cfg.binDir & " in PATH. You will need to add it " &
         "before you can use the generated launchers.")
  elif pathReport.shadowedSystemDirs.len > 0:
    warn(cfg.binDir & " has a higher precedence than these paths in your " &
         "PATH. This may present a security risk by allowing flatpaks to " &
         "override trusted system commands: " &
         pathReport.shadowedSystemDirs.join(", "))

  # --- Summary -----------------------------------------------------------
  if not cfg.quiet:
    stdout.writeLine("")
    stdout.writeLine("Applications: " & $counters.apps &
                     "   Launchers written: " & $counters.written &
                     "   Removed: " & $counters.removed &
                     "   Skipped: " & $counters.skipped &
                     "   Collisions: " & $counters.collisions &
                     "   Warnings: " & $gWarnings)

  if counters.collisions > 0:
    return 1
  if cfg.strict and gWarnings > 0:
    return 1
  0

# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

proc main(): int =
  let parsed = parseArgs(commandLineParams())
  if not parsed.ok:
    return parsed.code
  if parsed.cfg.showHelp:
    stdout.write(HelpText)
    return 0
  if parsed.cfg.showVersion:
    stdout.writeLine(ProgramName & " " & Version)
    return 0
  run(parsed.cfg)

when isMainModule:
  quit(main())
